#include "../../codexion.h"

void	swap_queue_coders(t_coder **a, t_coder **b)
{
	t_coder *temp;

	write(1, "a", 1);
	temp = *a;
	*a = *b;
	*b = temp;
	write(1, "a", 1);
}
