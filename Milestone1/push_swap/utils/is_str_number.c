#include "push_swap.h"

int	is_str_number(const char *s)
{
	int	i;

	if (!s || !*s)
		return (0);
	i = 0;
	if (s[0] == '+' || s[0] == '-')
	{
		if (!s[1])
			return (0);
		i = 1;
	}
	while (s[i])
	{
		if (s[i] < '0' || s[i] > '9')
			return (0);
		i++;
	}
	return (1);
}
